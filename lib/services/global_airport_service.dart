  // Calculate distance between two airports in km using Haversine formula
  static double calculateDistanceKm(AirportInfo a1, AirportInfo a2) {
    const p = 0.017453292519943295; // pi / 180
    final c = cos;
    final a = 0.5 - c((a2.latitude - a1.latitude) * p) / 2 +
        c(a1.latitude * p) * c(a2.latitude * p) *
            (1 - c((a2.longitude - a1.longitude) * p)) / 2;
    return 12742 * asin(sqrt(a)); // Diameter of earth * asin(sqrt(a))
  }

  // Search airports by query (city name, IATA code, country, or airport name)
  static List<AirportInfo> searchAirports(String query) {
    if (query.trim().isEmpty) return globalAirports.take(10).toList();
    String q = query.toLowerCase().trim();

    return globalAirports.where((a) {
      return a.iata.toLowerCase().contains(q) ||
          a.city.toLowerCase().contains(q) ||
          a.name.toLowerCase().contains(q) ||
          a.country.toLowerCase().contains(q);
    }).toList();
  }

  // Find exact airport by IATA code or return default
  static AirportInfo findByIata(String iata) {
    return globalAirports.firstWhere(
      (a) => a.iata.toUpperCase() == iata.toUpperCase(),
      orElse: () => AirportInfo(
        iata: iata.toUpperCase(),
        icao: 'ICAO',
        name: '$iata International Airport',
        city: iata.toUpperCase(),
        country: 'Global',
        latitude: 13.0,
        longitude: 80.0,
        terminal: 'Terminal 1',
        gate: 'Gate 1',
        time: DateTime.now(),
      ),
    );
  }
